package first.robot.mechanisms;

import static org.wpilib.units.Units.Amps;
import static org.wpilib.units.Units.KilogramSquareMeters;
import static org.wpilib.units.Units.Meters;
import static org.wpilib.units.Units.Seconds;

import com.ctre.phoenix6.CANBus;
import com.ctre.phoenix6.hardware.TalonFX;
import org.wpilib.command3.Command;
import org.wpilib.command3.Mechanism;
import org.wpilib.command3.Trigger;
import org.wpilib.hardware.bus.CANPort;
import org.wpilib.math.controller.SimpleMotorFeedforward;
import org.wpilib.math.system.DCMotor;
import org.wpilib.units.measure.AngularVelocity;
import yams.commands3.config.SmartMotorControllerConfig;
import yams.commands3.mechanisms.FlyWheel;
import yams.core.gearing.MechanismGearing;
import yams.core.mechanisms.config.FlyWheelConfig;
import yams.core.motorcontrollers.SmartMotorController;
import yams.core.motorcontrollers.enums.ControlMode;
import yams.core.motorcontrollers.enums.MotorMode;
import yams.core.motorcontrollers.remote.TalonFXWrapper;
import yams.core.telemetry.enums.TelemetryVerbosity;

/**
 * A flywheel, such as a shooter, driven by a Kraken X60 through a
 * TalonFX, using YAMS. Generated by YAMG.
 */
public class Flywheel implements Mechanism {

  // The vendor motor controller object: a Talon FX with CAN ID 1 on CAN bus CAN_S0.
  private final TalonFX talon = new TalonFX(1, new CANBus(CANPort.CAN_S0));

  // What the motor controller should do: its control mode, gains, gearing and limits.
  private final SmartMotorControllerConfig smcConfig =
    new SmartMotorControllerConfig(this)
      .withControlMode(ControlMode.CLOSED_LOOP)
      // Feedback constants (PID), in volts per rotation per second of error, on the real robot and in simulation.
      .withClosedLoopController(2.5, 0.0, 0.4)
      .withSimClosedLoopController(2.5, 0.0, 0.4)
      // Feedforward constants, in volts per rotation per second, on the real robot and in simulation.
      .withFeedforward(new SimpleMotorFeedforward(1.4, 0.0, 0.0))
      .withSimFeedforward(new SimpleMotorFeedforward(1.4, 0.0, 0.0))
      // Gearing from the motor rotor to the flywheel: 8.0 motor rotations per flywheel rotation.
      .withGearing(new MechanismGearing(8.0))
      // The flywheel's moment of inertia, used by the simulation.
      .withMomentOfInertia(KilogramSquareMeters.of(0.0001))
      .withMotorInverted(false)
      .withZeroPower(MotorMode.COAST)
      .withStatorCurrentLimit(Amps.of(80.0))
      .withSupplyCurrentLimit(Amps.of(60.0))
      // Telemetry name and how much to publish.
      .withTelemetry("FlywheelMotor", TelemetryVerbosity.HIGH);

  // The SmartMotorController applies the config to the Talon FX, which drives one Kraken X60.
  private final SmartMotorController motor = new TalonFXWrapper(
    talon,
    DCMotor.getKrakenX60(1),
    smcConfig
  );

  private final FlyWheelConfig flywheelConfig = new FlyWheelConfig()
    // The diameter of the wheel, used by the simulation.
    .withDiameter(Meters.of(0.1016))
    // Telemetry name and how much to publish.
    .withTelemetry("Flywheel", TelemetryVerbosity.HIGH);

  // The flywheel mechanism.
  private final FlyWheel flywheel = new FlyWheel(flywheelConfig, motor);

  /** Spin at a speed and hold it. This command does not end on its own. */
  public Command setVelocity(AngularVelocity speed) {
    return flywheel.run(speed);
  }

  /** Drive the flywheel with a duty cycle from -1 to 1. The closed loop is not used. */
  public Command set(double dutyCycle) {
    return flywheel.set(dutyCycle);
  }

  /** True while the flywheel is within a tolerance of a speed. */
  public Trigger near(AngularVelocity speed, AngularVelocity tolerance) {
    return flywheel.near(speed, tolerance);
  }

  /** Let the flywheel coast at the lowest priority, so that any other flywheel command can interrupt it. */
  public Command idle() {
    return run(coroutine -> coroutine.await(flywheel.set(0)))
      .withPriority(Command.LOWEST_PRIORITY)
      .named("Flywheel Idle");
  }

  /** Call this from Robot.robotPeriodic(), before the scheduler runs. */
  public void periodic() {
    // Publishes the flywheel's telemetry, and applies anything changed through live tuning.
    flywheel.updateTelemetry();
  }

  /** Call this from Robot.simulationPeriodic(). */
  public void simulationPeriodic() {
    // Runs the flywheel's physics simulation.
    flywheel.simIterate();
  }
}
